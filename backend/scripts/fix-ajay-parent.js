import mongoose from 'mongoose';
import Parent from '../src/models/Parent.js';
import Student from '../src/models/Student.js';
import Admission from '../src/models/Admission.js';
import { fallbackPortalEmail } from '../src/utils/generateCredentials.js';

const uri = process.env.MONGODB_URI;
if (!uri) {
  console.error('MONGODB_URI is required');
  process.exit(1);
}

const nameRegex = value => new RegExp(`^${value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'i');
const clean = value => String(value || '').trim();

await mongoose.connect(uri);

try {
  const ajay = await Parent.findOne({ fatherName: nameRegex('Ajay Singh Rajpoot') });
  if (!ajay) throw new Error('Ajay Singh Rajpoot parent record was not found');

  const tanishka = await Student.findOne({ studentName: nameRegex('Tanishka Singh Rajpoot') });
  if (!tanishka) throw new Error('Tanishka Singh Rajpoot student record was not found');

  const ekanshi = await Student.findOne({ studentName: nameRegex('Ekanshi Pant') });
  const ekanshiAdmission = await Admission.findOne({ studentName: nameRegex('Ekanshi Pant') }).sort('-createdAt');

  tanishka.parent = ajay._id;
  tanishka.fatherName = tanishka.fatherName || ajay.fatherName;
  tanishka.fatherPhone = tanishka.fatherPhone || ajay.fatherPhone;
  tanishka.address = tanishka.address || ajay.address;
  await tanishka.save({ validateBeforeSave: false });

  ajay.students = [tanishka._id];
  await ajay.save({ validateBeforeSave: false });

  if (ekanshi) {
    const fatherName = clean(process.env.EKANSHI_FATHER_NAME) || clean(ekanshiAdmission?.fatherName) || clean(ekanshi.fatherName) || clean(ekanshiAdmission?.parentName);
    const fatherPhone = clean(process.env.EKANSHI_FATHER_PHONE) || clean(ekanshiAdmission?.fatherPhone) || clean(ekanshi.fatherPhone) || clean(ekanshiAdmission?.phone) || clean(ekanshi.phone);
    const motherName = clean(ekanshiAdmission?.motherName) || clean(ekanshi.motherName);
    const motherPhone = clean(ekanshiAdmission?.motherPhone) || clean(ekanshi.motherPhone);

    ekanshi.fatherName = fatherName || ekanshi.fatherName;
    ekanshi.fatherPhone = fatherPhone || ekanshi.fatherPhone;
    ekanshi.motherName = motherName || ekanshi.motherName;
    ekanshi.motherPhone = motherPhone || ekanshi.motherPhone;
    ekanshi.parentName = fatherName || motherName || ekanshi.parentName;
    ekanshi.phone = fatherPhone || motherPhone || ekanshi.phone;

    let ekanshiParent = null;
    if (fatherPhone) ekanshiParent = await Parent.findOne({ fatherPhone });
    if (!ekanshiParent && fatherName) ekanshiParent = await Parent.findOne({ fatherName: nameRegex(fatherName) });

    if (!ekanshiParent) {
      ekanshiParent = await Parent.create({
        fatherName: fatherName || undefined,
        fatherPhone: fatherPhone || undefined,
        motherName: motherName || undefined,
        motherPhone: motherPhone || undefined,
        address: ekanshi.address || ekanshiAdmission?.address,
        students: [ekanshi._id],
        portalEmail: fallbackPortalEmail(fatherPhone || motherPhone || ekanshi.phone),
        isPortalActive: false,
        autoGenerated: false
      });
    }

    if (String(ekanshiParent._id) === String(ajay._id)) {
      ekanshi.parent = undefined;
    } else {
      ekanshi.parent = ekanshiParent._id;
      await Parent.findByIdAndUpdate(ekanshiParent._id, { $addToSet: { students: ekanshi._id } });
    }
    await ekanshi.save({ validateBeforeSave: false });
  }

  console.log('Fixed Ajay Singh Rajpoot parent link: only Tanishka Singh Rajpoot remains linked.');
  if (ekanshi) console.log('Ekanshi Pant father details restored from admission/env and removed from Ajay Singh Rajpoot children.');
} finally {
  await mongoose.disconnect();
}
